function [Best_score, Best_pos, Curve] = ACO(num_population, max_gen, X_min, Xmax, dimensions, fobj, G)
% =========================================================================
% ACO (ACOR): Continuous Ant Colony Optimization
% Used in the path-planning comparison experiments
% =========================================================================

% ACOR-specific parameters
ArchiveSize = num_population; % size of the solution archive
q = 0.5;                      % locality of the search (smaller -> faster convergence)
xi = 0.85;                    % convergence speed (scales the Gaussian standard deviation)

% Initialise the solution archive
Archive_pos = rand(ArchiveSize, dimensions) .* (Xmax - X_min) + X_min;
Archive_fitness = zeros(ArchiveSize, 1);

% Initial fitness
for i = 1:ArchiveSize
    Archive_fitness(i) = fobj(Archive_pos(i,:));
end

% Sort the archive by fitness, ascending (lower is better)
[Archive_fitness, SortOrder] = sort(Archive_fitness);
Archive_pos = Archive_pos(SortOrder, :);

% Record the global best
Best_pos = Archive_pos(1, :);
Best_score = Archive_fitness(1);
Curve = zeros(1, max_gen);

% Selection weights (Gaussian decay over rank)
weights = 1 ./ (q * ArchiveSize * sqrt(2 * pi)) .* exp(-0.5 * (((1:ArchiveSize) - 1) ./ (q * ArchiveSize)).^2);
probs = weights / sum(weights); % normalise to probabilities

% Main loop
for t = 1:max_gen
    % Paths generated by the new ants
    New_pos = zeros(num_population, dimensions);
    New_fitness = zeros(num_population, 1);
    
    for i = 1:num_population
        % 1. Choose a guiding archive solution by roulette wheel
        idx = RouletteWheelSelection(probs);
        
        for j = 1:dimensions
            % 2. Standard deviation sigma of dimension j (mean distance of all solutions to the guide)
            dx = abs(Archive_pos(:, j) - Archive_pos(idx, j));
            sigma = xi * sum(dx) / (ArchiveSize - 1);
            
            % 3. Sample the new position from a Gaussian
            New_pos(i, j) = Archive_pos(idx, j) + sigma * randn();
        end
        
        % Boundary check
        New_pos(i, :) = min(max(New_pos(i, :), X_min), Xmax);
        
        % Fitness of the new ants
        New_fitness(i) = fobj(New_pos(i, :));
    end
    
    % Merge the new solutions with the archive
    Combined_pos = [Archive_pos; New_pos];
    Combined_fitness = [Archive_fitness; New_fitness];
    
    % Re-sort the merged population
    [Combined_fitness, SortOrder] = sort(Combined_fitness);
    
    % Truncate: keep the best ArchiveSize solutions as the new archive
    Archive_pos = Combined_pos(SortOrder(1:ArchiveSize), :);
    Archive_fitness = Combined_fitness(1:ArchiveSize);
    
    % Update the global best
    Best_score = Archive_fitness(1);
    Best_pos = Archive_pos(1, :);
    
    % Best value of this generation
    Curve(t) = Best_score;
end

end

% =========================================================================
% Local function: roulette wheel selection
% =========================================================================
function index = RouletteWheelSelection(probs)
    accumulation = cumsum(probs);
    p = rand();
    index = find(accumulation >= p, 1);
    % Guard against round-off leaving no index
    if isempty(index)
        index = 1;
    end
end